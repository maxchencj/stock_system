class ThsSectorService:
    """同花顺行业数据服务"""

    @staticmethod
    def get_ths_industry_realtime() -> pd.DataFrame:
        """
        获取同花顺行业实时行情
        通过成分股计算行业涨跌幅（市值加权）
        """
        results = []

        for industry_name, stock_codes in THS_INDUSTRY_STOCKS.items():
            try:
                # 获取成分股行情
                df = TencentAPI.get_batch_quotes(stock_codes)

                if df.empty:
                    continue

                # 计算市值加权平均涨跌幅
                df['weight'] = df['market_cap'] / df['market_cap'].sum()
                weighted_change = (df['change_pct'] * df['weight']).sum()

                # 找出领涨股
                leader = df.nlargest(1, 'change_pct').iloc[0]

                # 计算平均量比
                avg_volume_ratio = df['volume_ratio'].mean()

                # 计算平均换手率
                avg_turnover = df['turnover_rate'].mean()

                # 统计涨跌家数
                up_count = len(df[df['change_pct'] > 0])
                down_count = len(df[df['change_pct'] < 0])

                results.append({
                    '板块名称': industry_name,
                    '涨跌幅': round(weighted_change, 2),
                    '领涨股票': leader['name'],
                    '领涨股票涨跌幅': round(leader['change_pct'], 2),
                    '平均量比': round(avg_volume_ratio, 2),
                    '平均换手率': round(avg_turnover, 2),
                    '上涨家数': up_count,
                    '下跌家数': down_count,
                    '成分股数': len(df),
                })

                logger.debug(f'计算{industry_name}行情: 涨跌幅{weighted_change:.2f}%')

            except Exception as e:
                logger.warning(f'计算{industry_name}行情失败: {e}')
                continue

        if results:
            df_result = pd.DataFrame(results)
            # 按涨跌幅排序
            df_result = df_result.sort_values('涨跌幅', ascending=False)
            logger.info(f'获取同花顺行业 {len(df_result)} 个')
            return df_result

        return pd.DataFrame()


